/**
 * build-en-syllables.mjs — generate en-syllables.js, the list of words the
 * English rules in syllables.js get wrong.
 *
 * English is the one language here where rules alone are not good enough: they
 * land around nine times in ten, and a count that is quietly off by one is
 * worse than no count. So we take the CMU Pronouncing Dictionary as ground
 * truth (a syllable is a phoneme carrying a stress digit), run our own rules
 * over the same words, and commit only the disagreements.
 *
 * That keeps the file small and, more usefully, makes it shrink whenever the
 * rules improve — the number it prints is a score for syllables.js, not just a
 * byte count. Nothing here runs in the browser or at page load; the output is
 * committed, and only edit mode on localhost ever fetches it.
 *
 *   node tools/build-en-syllables.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'https://raw.githubusercontent.com/cmusphinx/cmudict/master/cmudict.dict';

const syl = await import('../syllables.js').then((m) => m.default ?? m);

/* Ask syllables.js for its unaided guess: one word, no dictionary loaded. */
delete globalThis.EN_SYLLABLES;
const guess = (word) => syl.count(word, 'en');

console.log('fetching', SOURCE);
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`cmudict fetch failed: HTTP ${res.status}`);
const text = await res.text();

const truth = new Map();
for (const raw of text.split('\n')) {
  const line = raw.split('#')[0].trim();
  if (!line) continue;
  const [word, ...phones] = line.split(/\s+/);
  if (/\(\d\)$/.test(word)) continue;              /* an alternate pronunciation */
  const w = word.toLowerCase();
  /* possessives are just the stem plus a rule, and initialisms ("abc", "aaa")
     are spelled out in cmudict but never sung */
  if (!/^[a-z][a-z']*$/.test(w) || w.length < 2) continue;
  if (/'/.test(w)) continue;
  if (!/[aeiouy]/.test(w)) continue;
  const n = phones.filter((p) => /\d/.test(p)).length;
  if (n > 0 && !truth.has(w)) truth.set(w, n);
}
console.log(`cmudict: ${truth.size} usable words`);

const wrong = new Map();
let agree = 0;
for (const [w, n] of truth) {
  if (guess(w) === n) agree++;
  else wrong.set(w, n);
}
const pct = ((agree / truth.size) * 100).toFixed(2);
console.log(`rules alone agree on ${agree}/${truth.size} (${pct}%)`);
console.log(`writing ${wrong.size} corrections`);

/* Grouped by count and space-joined: the same words as a JSON object would cost
   several times as much, and this unpacks in one pass at load. */
const byCount = new Map();
for (const [w, n] of [...wrong].sort((a, b) => a[0].localeCompare(b[0]))) {
  if (!byCount.has(n)) byCount.set(n, []);
  byCount.get(n).push(w);
}
const rows = [...byCount.keys()].sort((a, b) => a - b)
  .map((n) => `    ${n}: '${byCount.get(n).join(' ')}'`).join(',\n');

const out = `/**
 * en-syllables.js — the English words that the rules in syllables.js count
 * wrongly, with their true syllable count.
 *
 * GENERATED by tools/build-en-syllables.mjs from the CMU Pronouncing
 * Dictionary. Do not edit by hand; run the tool again instead.
 *
 * Rules alone agreed with cmudict on ${pct}% of ${truth.size} words, so this
 * carries the remaining ${wrong.size}. It is loaded only by edit mode on
 * localhost, never by a published copy of the site.
 */
(function (root) {
  'use strict';

  var DATA = {
${rows}
  };

  var map = null;

  function build() {
    map = Object.create(null);
    for (var n in DATA) {
      if (!Object.prototype.hasOwnProperty.call(DATA, n)) continue;
      var words = DATA[n].split(' ');
      for (var i = 0; i < words.length; i++) map[words[i]] = +n;
    }
  }

  root.EN_SYLLABLES = {
    get: function (word) {
      if (!map) build();
      return map[word];
    }
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

const dest = join(ROOT, 'en-syllables.js');
writeFileSync(dest, out, 'utf8');
console.log(`wrote ${dest} (${(out.length / 1024).toFixed(0)} KB)`);
